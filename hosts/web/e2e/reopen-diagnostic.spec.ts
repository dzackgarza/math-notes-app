import { test, expect } from './native-desktop.ts';
import { enterText, boxOf, closePopover, penStroke, line, save, capture } from './workflow-actions.ts';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
test('diagnose thin ink redraw and reopen', async ({desktop},info)=>{
 test.setTimeout(240000);
 let page=desktop.page;
 const button=(name:string)=>page.getByRole('button',{name,exact:true});
 await desktop.chooseFolder();
 await button('New notebook').click();
 await enterText(page.getByRole('textbox',{name:'Notebook title',exact:true}),'Diagnostic');
 await button('Create').click(); await button('New note').click();
 await enterText(page.getByRole('textbox',{name:'Title',exact:true}),'Thin ink');
 await button('Plain').click(); await button('A4').click(); await button('Create').click();
 const canvas=page.locator('canvas[id^="ink-canvas-"]:visible');await canvas.waitFor();
 const box=await boxOf(canvas); const region={x:box.x+140,y:box.y+100,width:460,height:420};
 await button('Pen').click();await button('0.6 pt').click();await closePopover(page);
 const cdp=await page.context().newCDPSession(page);
 await penStroke(cdp,line(box.x+180,box.x+300,box.y+125),.5);
 await save(page);await expect(page.getByRole('status',{name:/^Notebook save/})).toHaveAccessibleName('Notebook save Saved',{timeout:30000});
 const path=join(desktop.notes,'Diagnostic','Thin ink','pages','0001.svg');
 const original=await readFile(path,'utf8');await writeFile(info.outputPath('original.svg'),original);
 const before=await capture(page,region);await page.screenshot({path:info.outputPath('before.png')});
 await page.setViewportSize({width:1270,height:900});await expect(canvas).toBeVisible();
 await page.setViewportSize({width:1280,height:900});await expect.poll(()=>boxOf(canvas)).toEqual(box);
 const redraw=await capture(page,region);await page.screenshot({path:info.outputPath('redraw.png')});
 page=await desktop.restart();await button('Reconnect folder').click();await desktop.allow('Allow this time');
 await page.getByRole('button',{name:/^Open Diagnostic/}).click();await page.getByRole('button',{name:/^Open Thin ink/}).click();
 await page.locator('canvas[id^="ink-canvas-"]:visible').waitFor();
 const reopened=await capture(page,region);await page.screenshot({path:info.outputPath('reopened.png')});
 const diff=(a:number[][],b:number[][])=>{let pixels=0,max=0;for(let i=0;i<a.length;i++){const d=Math.max(...a[i].map((c,k)=>Math.abs(c-b[i][k])));if(d)pixels++;max=Math.max(max,d);}return {pixels,max};};
 page=await desktop.restart();await button('Reconnect folder').click();await desktop.allow('Allow this time');
 await page.getByRole('button',{name:/^Open Diagnostic/}).click();await page.getByRole('button',{name:/^Open Thin ink/}).click();
 await page.locator('canvas[id^="ink-canvas-"]:visible').waitFor();
 const reopenedAgain=await capture(page,region);
 await writeFile(info.outputPath('observations.json'),JSON.stringify({reopenRepeat:diff(reopened,reopenedAgain),sameFile:original===await readFile(path,'utf8'),beforeRedraw:diff(before,redraw),beforeReopen:diff(before,reopened),redrawReopen:diff(redraw,reopened)},null,2));
 expect(diff(before,reopened).pixels, 'saved ink paints the same pixels after a real reopen').toBe(0);
});
